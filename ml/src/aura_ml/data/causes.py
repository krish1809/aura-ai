_MAKES_ME = re.compile(
    rf"\b(?:makes|made|making|make|has made|is making|gives|gave)\s+me\s+(?:feel\s+)?"
    rf"(?:so\s+|really\s+|very\s+|a lot of\s+|such\s+)?(?:{_TRIG}|anxiety|stress|depression)\b",
    re.IGNORECASE,
)
_BACKWARD = re.compile(
    r"\s*(?:,\s*)?\b(?:so|that's why|thats why|which is why|therefore|and now)\s+(?=(?:i|i'm|im|i've|i am)\b)",
    re.IGNORECASE,
)


@dataclass(frozen=True)
class CauseSpan:
    start: int
    end: int
    text: str
    rule: str


def _trim(text: str, start: int, end: int) -> tuple[int, int]:
    while start < end and text[start] in " ,\"'-:":
        start += 1
    while end > start and text[end - 1] in " ,.!?;:\"'-":
        end -= 1
    return start, end


def _valid(text: str, start: int, end: int, min_words: int, max_words: int = 30) -> bool:
    span = text[start:end].strip().lower()
    n = len(span.split())
    return min_words <= n <= max_words and span not in _NON_CAUSES


def _sentence_has_feeling(text: str, pos: int) -> bool:
    for m in _SENTENCE.finditer(text):
        if m.start() <= pos < max(m.end(), m.start() + 1):
            return bool(_FEEL.search(m.group()))
    return bool(_FEEL.search(text))


def _clause_before(text: str, end: int) -> int:
    start = 0
    for m in _CLAUSE_START.finditer(text, 0, end):
        start = m.end()
    return start


def _candidates(text: str) -> list[tuple[int, CauseSpan]]:
    out: list[tuple[int, CauseSpan]] = []
    for rule, prio, pattern, needs_feeling in _FORWARD:
        for m in pattern.finditer(text):
            if needs_feeling and not _sentence_has_feeling(text, m.start()):
                continue
            end_m = _CLAUSE_END.search(text, m.end())
            s, e = _trim(text, m.end(), end_m.start() if end_m else len(text))
            if _valid(text, s, e, min_words=1 if rule in ("emotion_trigger", "due_to") else 2):
                out.append((prio, CauseSpan(s, e, text[s:e], rule)))
    for m in _MAKES_ME.finditer(text):
        s, e = _trim(text, _clause_before(text, m.start()), m.start())
        if text[s:e].strip().lower() in _NON_CAUSES and s > 0:
            # "My boss yells at me and it makes me feel worthless": the cause is the clause before "it"
            prev_end = len(re.sub(r"(?:\s+and)?[\s,]*$", "", text[:s]))
            s, e = _trim(text, _clause_before(text, prev_end), prev_end)
        if _valid(text, s, e, min_words=2):
            out.append((2, CauseSpan(s, e, text[s:e], "makes_me")))
    for m in _BACKWARD.finditer(text):
        if not _FEEL.search(text[m.end() : m.end() + 80]):
            continue
        s, e = _trim(text, _clause_before(text, m.start()), m.start())
        if _valid(text, s, e, min_words=3):
            out.append((3, CauseSpan(s, e, text[s:e], "backward")))
    return out


def extract_causes(text: str) -> list[CauseSpan]:
    """All non-overlapping explicit cause spans in `text`, in reading order."""
    chosen: list[CauseSpan] = []
    for _, cand in sorted(_candidates(text), key=lambda pc: (pc[0], pc[1].start)):
        if all(cand.end <= c.start or cand.start >= c.end for c in chosen):
            chosen.append(cand)
    return sorted(chosen, key=lambda c: c.start)


def extract_cause(text: str) -> CauseSpan | None:
    spans = extract_causes(text)
    return spans[0] if spans else None


_PHATIC = re.compile(
    r"^(?:hi|hello|hey|thanks?|thank you|ok(?:ay)?|yes|yeah|yep|no|nope|sure|bye|good ?bye|"
    r"you too|same to you|i see|right|true|exactly|lol|hmm+)\b[\s!.?,]*$",
    re.IGNORECASE,
)


def is_phatic(text: str) -> bool:
    return bool(_PHATIC.match(text.strip())) or len(text.split()) < 3
