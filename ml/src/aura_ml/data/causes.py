"""Rule-based *explicit* emotion-cause extraction used to create silver labels.

ESConv has no cause annotations, so the ECE training data is generated by these
rules and the RoBERTa model learns to generalise them. Compared with the 2025
version this extractor is deliberately high-precision:

* only markers that really signal causation are used ("because", "worried about",
  "makes me sad", "ever since"...) - not "to", "for", "on", "as";
* "because"/"since"/"due to" only count when the sentence talks about a feeling,
  so reasons for actions ("I'll call him because he asked") are not labelled;
* backward markers ("..., so I'm sad", "X makes me anxious") take the clause
  *before* the marker instead of the one after it;
* all non-overlapping cause spans in an utterance are returned (multi-span BIO);
* utterances with no explicit cause become negative examples.

Every function works on character offsets into the original utterance, which is
what the BIO aligner and the evaluator use.
"""

